"""TailTrail on the Sturman et al. (2020) open field pilot videos.

This script prepares settings and analyses the historical GUI exports. For
unattended tracking with the installed TailTrail engine, use
``scripts/tailtrail_batch.py`` (see ``reports/tailtrail_batch.md``).

``sheet``    Writes reports/zenodo_pilot/tailtrail/setup.csv (+ setup.md): per video the
             TailTrail settings that reproduce the pilot's set-up as closely as
             TailTrail allows -- analysis window, distance scale, and the pilot's
             zones as axis-aligned Rectangle ROIs (TailTrail has no polygons; the
             camera sees the arena slightly rotated and in perspective).

``analyse``  Reads what the GUI run produced in reports/zenodo_pilot/tailtrail/:
               data.xlsx            TailTrail's export (all 4 videos)
               settings/<video>     File > Save Settings after each video (optional
                                    but recommended: then the ROIs TailTrail really
                                    used are read back instead of assumed)
             and writes metrics.csv / agreement.csv there.  DLC and RATEL are
             re-scored with TailTrail's ROIs, so all three tools share one zone
             geometry; agreement is against DLC, as in the rest of the pilot.

Usage:  .venv/Scripts/python scripts/zenodo_tailtrail.py sheet
        .venv/Scripts/python scripts/zenodo_tailtrail.py analyse
"""

from __future__ import annotations

import argparse
import copy
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from behaviour.adapters.tailtrail import read_data_xlsx, read_settings, settings_to_toml
from behaviour.compare import compare
from behaviour.config import load_config
from behaviour.metrics import metrics_for_trajectory
from behaviour.trajectory import load_trajectory

ROOT = Path(__file__).resolve().parents[1]
VIDEOS = ROOT / "videos" / "zenodo_3608658"
OFT = ROOT / "reports" / "zenodo_pilot" / "oft"
TT = ROOT / "reports" / "zenodo_pilot" / "tailtrail"
FRAME_W, FRAME_H = 928, 576
MASK_MARGIN_PX = 10
MIN_AREA_PX = 600       # TailTrail "Min tracking area"; the mouse is ~1300 px
BG_VAR_THRESHOLD = 64.0  # TailTrail "Var threshold" (default 32)
TIMESTAMP_REACH = 262  # px from frame centre to the nearest corner of the burnt-in clock (585, 55)


def rectangle(points: np.ndarray) -> dict:
    """Axis-aligned rectangle through the mean of opposite edges of a tl, tr, br, bl quadrilateral."""
    tl, tr, br, bl = points
    left, right = (tl[0] + bl[0]) / 2, (tr[0] + br[0]) / 2
    top, bottom = (tl[1] + tr[1]) / 2, (bl[1] + br[1]) / 2
    return dict(x=round(left), y=round(top), width=round(right - left), height=round(bottom - top))


def video_ids() -> list[str]:
    return sorted(p.stem for p in (OFT / "configs").glob("*.toml"))


def sheet():
    TT.mkdir(parents=True, exist_ok=True)
    rows = []
    for vid in video_ids():
        cfg = load_config(OFT / "configs" / f"{vid}.toml")
        row = dict(video=f"{vid}.mp4", start_s=round(cfg.start_s, 2),
                   end_s=round(cfg.start_s + cfg.duration_s, 2), scale_px_per_m=round(cfg.px_per_m, 2),
                   hysteresis_m=round(cfg.zones[0].hysteresis_px / cfg.px_per_m, 3))
        corners = []
        for z in cfg.zones:  # center first: TailTrail needs the smaller overlapping ROI on top
            r = rectangle(np.asarray(z.points, float))
            row.update({f"{z.name}_{k}": v for k, v in r.items()})
            corners += [(r["x"], r["y"]), (r["x"] + r["width"], r["y"] + r["height"]),
                        (r["x"], r["y"] + r["height"]), (r["x"] + r["width"], r["y"])]
        # TailTrail's mask is a circle around the frame centre; it must contain the whole periphery ROI
        reach = max(np.hypot(x - FRAME_W / 2, y - FRAME_H / 2) for x, y in corners)
        row["mask_radius"] = int(np.ceil(reach + MASK_MARGIN_PX))
        rows.append(row)
    df = pd.DataFrame(rows)
    df.to_csv(TT / "setup.csv", index=False)

    md = ["# TailTrail settings for the pilot OFT videos",
          "",
          "Generated by `scripts/zenodo_tailtrail.py sheet`. Same for every video:",
          "",
          "- Bg subtraction: tick **Invert colors** (dark mouse on a light floor) *before* Train algorithm.",
          "- ROI config: delete the default ROIs; add `center` then `periphery` (center on top), "
          "type Rectangle, hysteresis as below.",
          "- Translate / rotate frame: leave at 0 (the pilot's zones are in raw frame pixels).",
          "- Export folder: `reports/zenodo_pilot/tailtrail` (data.xlsx collects one row per video).",
          "- After each video: File > Save Settings as `reports/zenodo_pilot/tailtrail/settings/<video>` "
          "(e.g. `settings/OFT_5`), so the analysis reads back the ROIs actually used.",
          "- Rectangle X/Y below assume TailTrail's X/Y is the top-left corner. If the ROI shows up "
          "shifted by half its size, X/Y is the centre: use the `cx/cy` columns instead.",
          f"- The camera's clock (top right, changes every second) is within ~{TIMESTAMP_REACH} px of the "
          "frame centre, so the mask radius below includes it. If the tracking cursor jumps there, lower "
          f"the mask radius to {TIMESTAMP_REACH - 5} (cuts the outer corners of the periphery ROI; note it).",
          ""]
    for r in rows:
        md += [f"## {r['video']}", "",
               f"- Timeline: left marker {r['start_s']} s, right marker {r['end_s']} s",
               f"- Distance scale: {r['scale_px_per_m']} px/m; mask radius {r['mask_radius']}",
               "", "| ROI | X | Y | width | height | cx | cy | hysteresis (m) |", "|---|---|---|---|---|---|---|---|"]
        for z in ("center", "periphery"):
            x, y, w, h = (r[f"{z}_{k}"] for k in ("x", "y", "width", "height"))
            md.append(f"| {z} | {x} | {y} | {w} | {h} | {x + w // 2} | {y + h // 2} | {r['hysteresis_m']} |")
        md.append("")
    (TT / "setup.md").write_text("\n".join(md), encoding="utf-8")
    print(df.to_string(index=False))
    print("wrote", TT / "setup.csv", "and setup.md")


def make_settings(template: str):
    """One loadable TailTrail settings file per video, from a file saved in TailTrail (the template)."""
    from behaviour.adapters.tailtrail import dump_settings, load_raw_settings, rectangle_contours
    (TT / "settings").mkdir(parents=True, exist_ok=True)
    for r in pd.read_csv(TT / "setup.csv").itertuples():
        raw = load_raw_settings(template)
        # min_area / bg_var_threshold raised from 50 / 32 after the first runs: those detected
        # wall reflections and noise as the animal (OFT_6 losses 860 -> 765)
        raw.update(scale=float(r.scale_px_per_m), mask_radius=int(r.mask_radius), bg_invert_colors=True,
                   min_area=MIN_AREA_PX, bg_var_threshold=BG_VAR_THRESHOLD,
                   translate_frame_x=0, translate_frame_y=0, rotate_frame=0,
                   results_path=TT.as_posix())
        rois = {roi.name.lower(): roi for roi in raw["rois"]}
        for z in ("center", "periphery"):
            roi = rois[z]
            x, y, w, h = (int(getattr(r, f"{z}_{k}")) for k in ("x", "y", "width", "height"))
            roi.type, roi.x, roi.y, roi.width, roi.height, roi.hysteresis = "Rectangle", x, y, w, h, float(r.hysteresis_m)
            # band at this video's scale (truncated, as TailTrail did: 0.01 m * 266.66 -> 2 px)
            roi.contour, roi.hysteresis_contour = rectangle_contours(x, y, w, h, int(r.hysteresis_m * r.scale_px_per_m))
        out = TT / "settings" / Path(r.video).stem
        dump_settings(raw, out)
        print("wrote", out)


def tailtrail_config(vid: str, base):
    """Pilot config for ``vid`` with the zones TailTrail used (saved settings, else the sheet)."""
    cfg = copy.deepcopy(base)
    saved = sorted((TT / "settings").glob(f"{vid}*")) if (TT / "settings").exists() else []
    if saved:
        s = read_settings(saved[0])
        if any(s.get(k, 0) for k in ("translate_frame_x", "translate_frame_y", "rotate_frame")):
            warnings.warn(f"{vid}: TailTrail settings transform the frame; its ROIs are not in raw "
                          "frame pixels and will not line up with DLC/RATEL", stacklevel=2)
        if abs(float(s["scale"]) - cfg.px_per_m) > 0.01 * cfg.px_per_m:
            warnings.warn(f"{vid}: TailTrail scale {s['scale']} px/m differs from the pilot's "
                          f"{cfg.px_per_m:.2f}", stacklevel=2)
        path = TT / "configs" / f"{vid}.toml"
        path.parent.mkdir(exist_ok=True)
        path.write_text(settings_to_toml(s, saved[0].name), encoding="utf-8")
        tt = load_config(path)
        cfg.zones, source = tt.zones, f"settings/{saved[0].name}"
    else:
        sh = pd.read_csv(TT / "setup.csv").set_index("video").loc[f"{vid}.mp4"]
        from behaviour.zones import RectangleZone
        h_px = float(sh.hysteresis_m) * cfg.px_per_m
        cfg.zones = [RectangleZone(z, h_px, x=sh[f"{z}_x"], y=sh[f"{z}_y"],
                                   width=sh[f"{z}_width"], height=sh[f"{z}_height"])
                     for z in ("center", "periphery")]
        source = "setup.csv (assumed)"
        warnings.warn(f"{vid}: no saved TailTrail settings; assuming the ROIs in setup.csv", stacklevel=2)
    return cfg, source


def analyse():
    xlsx = TT / "data.xlsx"
    if not xlsx.exists():
        raise SystemExit(f"{xlsx} not found: run TailTrail on the videos in setup.md and export there first")
    base = {vid: load_config(OFT / "configs" / f"{vid}.toml") for vid in video_ids()}
    tt = read_data_xlsx(xlsx, next(iter(base.values())))  # same zone names and start zone for all
    missing = set(base) - set(tt.video_id)
    if missing:
        warnings.warn(f"data.xlsx has no row for {sorted(missing)}", stacklevel=2)

    longs, info = [tt], []
    for vid in sorted(set(tt.video_id) & set(base)):
        cfg, source = tailtrail_config(vid, base[vid])
        for tool in ("dlc", "opencv"):
            longs.append(metrics_for_trajectory(load_trajectory(OFT / "tracks" / tool / f"{vid}.csv"),
                                                cfg, vid, tool))
        q = tt[(tt.video_id == vid) & (tt.kind == "quality")].set_index("metric")["value"]
        info.append(dict(video_id=vid, roi_source=source, window_s=cfg.session(vid).duration_s,
                         tailtrail_time_s=q.get("duration_s"), losses=q.get("losses"),
                         unassigned_s=q.get("unassigned_time_s")))
    long = pd.concat(longs, ignore_index=True)
    long.to_csv(TT / "metrics.csv", index=False)
    pd.DataFrame(info).to_csv(TT / "runs.csv", index=False)
    agr = compare(long, reference="dlc")
    agr.to_csv(TT / "agreement.csv", index=False)
    with pd.option_context("display.width", 200, "display.precision", 3):
        print(pd.DataFrame(info).to_string(index=False))
        print(agr[["metric", "zone", "tool_b", "n", "mean_a", "mean_b", "bias", "bias_pct", "ccc"]].to_string(index=False))
    print("wrote", TT)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["sheet", "settings", "analyse"])
    ap.add_argument("--template", default=str(ROOT / "tail-trail" / "settings" / "OFT_5"),
                    help="settings file saved in TailTrail, for `settings`")
    a = ap.parse_args()
    if a.step == "settings":
        make_settings(a.template)
    else:
        {"sheet": sheet, "analyse": analyse}[a.step]()


if __name__ == "__main__":
    main()
