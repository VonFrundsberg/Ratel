"""Pilot on public data: the RATEL tracker vs DeepLabCut on the Sturman et al.
(2020) open field videos (zenodo.org/records/3608658, DLC output and labels from
github.com/ETHZ-INS/DLCAnalyzer).

Per video:
  * zones from DLC's median arena corners (tl, tr, br, bl): "center" = arena
    polygon scaled by CENTER_SCALE around its centroid, "periphery" = rest of the
    arena polygon scaled by PERIPHERY_SCALE (reaches onto the walls)
    (the camera moved between sessions, so geometry is per video)
  * px_per_m from the mean arena side length and ARENA_SIDE_M
  * analysis window from the raters' Start/End labels (median over raters)

Outputs (in OUT): configs/, tracks/{opencv,dlc}/, metrics.csv, agreement.csv,
positions.csv (frame-by-frame opencv vs DLC position error).

Usage:  .venv/Scripts/python scripts/zenodo_pilot.py [--qc] [--retrack]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from behaviour.adapters import deeplabcut as dlc
from behaviour.compare import compare
from behaviour.config import load_config
from behaviour.metrics import metrics_for_trajectory
from behaviour.trackers.opencv_tracker import TrackerParams, track
from behaviour.trajectory import load_trajectory

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "videos" / "zenodo_3608658"
OUT = ROOT / "output" / "zenodo_pilot"
FPS = 25.0
ARENA_SIDE_M = 0.42   # assumed; only scales distances, identical for both tools
CENTER_SCALE = 0.5
PERIPHERY_SCALE = 1.1  # outer zone reaches past the walls so rearing on them stays "in" (TailTrail manual)
HYSTERESIS_M = 0.01


def window_from_labels(labels: pd.DataFrame, vid: str) -> tuple[float, float]:
    s = labels[(labels.ID == vid) & labels.type.str.match(r"Start.?End")]
    per_rater = s.groupby("Experimenter")["from"].agg(["min", "max"])
    start, end = per_rater["min"].median(), per_rater["max"].median()
    return float(start), float(end - start)


def write_config(path: Path, corners: np.ndarray, start_s: float, duration_s: float) -> None:
    centroid = corners.mean(axis=0)
    center = centroid + CENTER_SCALE * (corners - centroid)
    periphery = centroid + PERIPHERY_SCALE * (corners - centroid)
    side_px = np.mean([np.linalg.norm(corners[i] - corners[(i + 1) % 4]) for i in range(4)])
    pts = lambda a: ", ".join(f"[{x:.1f}, {y:.1f}]" for x, y in a)
    path.write_text(f"""# generated by scripts/zenodo_pilot.py
[video]
px_per_m = {side_px / ARENA_SIDE_M:.2f}
mask_margin_px = 10.0

[window]
start_s = {start_s:.3f}
duration_s = {duration_s:.3f}

[protocol]
start_zone = "periphery"

[zone_rules]
hysteresis_m = {HYSTERESIS_M}
hysteresis_mode = "outer"

[tracker]
min_area_px = 150
max_area_px = 5000     # mouse is ~1300 px

[[zones]]
name = "center"
shape = "polygon"
points = [{pts(center)}]

[[zones]]
name = "periphery"
shape = "polygon"
points = [{pts(periphery)}]
""", encoding="utf-8")


def position_agreement(a: pd.DataFrame, b: pd.DataFrame, max_lag: int = 15) -> dict:
    """Median distance between two tools' positions, at the best frame lag."""
    n = min(len(a), len(b))
    ax, ay = a.x_px.to_numpy()[:n], a.y_px.to_numpy()[:n]
    bx, by = b.x_px.to_numpy()[:n], b.y_px.to_numpy()[:n]
    best = None
    for lag in range(-max_lag, max_lag + 1):
        sa = slice(max(lag, 0), n + min(lag, 0))
        sb = slice(max(-lag, 0), n - max(lag, 0))
        d = np.hypot(ax[sa] - bx[sb], ay[sa] - by[sb])
        med = np.nanmedian(d)
        if best is None or med < best[1]:
            best = (lag, med, d)
    lag, med, d = best
    return dict(frames_a=len(a), frames_b=len(b), best_lag_frames=lag, median_px=med,
                p95_px=np.nanpercentile(d, 95), both_valid=float(np.isfinite(d).mean()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qc", action="store_true", help="write annotated QC videos")
    ap.add_argument("--retrack", action="store_true", help="rerun the tracker even if tracks exist")
    a = ap.parse_args()

    labels = pd.read_csv(DATA / "labels" / "AllLabDataOFT_final.csv", sep=";")
    mapping = pd.read_csv(DATA / "oft_dlc_map.csv")
    for d in ("configs", "tracks/opencv", "tracks/dlc"):
        (OUT / d).mkdir(parents=True, exist_ok=True)

    longs, positions = [], []
    for vid, dlc_file in mapping.sort_values("ID").values:
        dlc_path = DATA / "dlc" / dlc_file
        corners = dlc.landmarks(dlc_path, ["tl", "tr", "br", "bl"])
        start, dur = window_from_labels(labels, vid)
        cfg_path = OUT / "configs" / f"{vid}.toml"
        write_config(cfg_path, corners, start, dur)
        cfg = load_config(cfg_path)

        oc_path = OUT / "tracks" / "opencv" / f"{vid}.csv"
        if a.retrack or not oc_path.exists():
            qc = OUT / "tracks" / "opencv" / f"{vid}_qc.mp4" if a.qc else None
            track(DATA / f"{vid}.mp4", cfg.zones, TrackerParams.from_dict(cfg.tracker),
                  cfg.mask_margin_px, qc_video=qc).to_csv(oc_path, index=False)
        oc = load_trajectory(oc_path)
        dl = dlc.trajectory(dlc_path, FPS)
        dl.to_csv(OUT / "tracks" / "dlc" / f"{vid}.csv", index=False)

        longs += [metrics_for_trajectory(oc, cfg, vid, "opencv"), metrics_for_trajectory(dl, cfg, vid, "dlc")]
        positions.append(dict(video_id=vid, window_s=f"{start:.1f}+{dur:.1f}",
                              opencv_tracked=oc.x_px.notna().mean(), **position_agreement(oc, dl)))
        print(f"{vid}: done")

    long = pd.concat(longs, ignore_index=True)
    long.to_csv(OUT / "metrics.csv", index=False)
    pos = pd.DataFrame(positions)
    pos.to_csv(OUT / "positions.csv", index=False)
    agr = compare(long, reference="dlc")
    agr.to_csv(OUT / "agreement.csv", index=False)

    with pd.option_context("display.width", 200, "display.precision", 3, "display.max_rows", 100):
        print("\nPosition agreement (opencv vs DLC bodycentre):")
        print(pos.to_string(index=False))
        print("\nPer-video metrics:")
        beh = long[long.kind == "behaviour"].pivot_table(index=["metric", "zone"], columns=["video_id", "tool"], values="value")
        print(beh.to_string())
        print("\nAgreement (a = dlc, b = opencv):")
        print(agr[["metric", "zone", "n", "mean_a", "mean_b", "bias", "bias_pct", "pearson_r", "ccc", "icc_a1"]].to_string(index=False))
        q = long[long.kind == "quality"].pivot_table(index=["metric"], columns=["video_id", "tool"], values="value")
        print("\nQuality:")
        print(q.to_string())


if __name__ == "__main__":
    main()
