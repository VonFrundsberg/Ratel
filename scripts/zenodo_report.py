def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--retrack", action="store_true")
    a = ap.parse_args()
    GEN.mkdir(parents=True, exist_ok=True)
    (REP / "fst" / "tracks").mkdir(parents=True, exist_ok=True)
    N = Numbers()

    cfg = load_config(FST_CFG)
    events, windows, raters = read_fst_labels()
    cfg.sessions = {v: Session(s, d, None) for v, (s, d) in windows.items()}
    rater_names = sorted(raters.values())

    # ---- 1. inter-rater reliability (10 videos)
    hum = rater_long(events, cfg)
    hum.to_csv(GEN / "fst_human_metrics.csv", index=False)
    labelled = sorted(windows, key=lambda v: int(v.split("_")[1]))
    N["nFstLabelled"] = len(labelled)
    N["nRaters"] = len(rater_names)
    N["fstWindowMedian"] = fmt(np.median([d for _, d in windows.values()]), 0)

    rel_rows = []
    for metric, label, nd in [("fst_immobile_s", "Immobility (s)", 1),
                              ("fst_immobility_latency_s", "Latency to immobility (s)", 1),
                              ("fst_immobile_bins", "Immobile 5-s bins", 1)]:
        w = hum[hum.metric == metric].pivot(index="video_id", columns="tool", values="value").loc[labelled, rater_names]
        y = w.to_numpy(float)
        ccc = [lins_ccc(*[y[:, i], y[:, j]]) for i, j in combinations(range(len(rater_names)), 2)]
        icc = icc_a1_k(y)
        rel_rows.append([label] + [f"{fmt(np.nanmean(y[:, k]), nd)} ({fmt(np.nanstd(y[:, k], ddof=1), nd)})"
                                   for k in range(len(rater_names))]
                        + [fmt(icc, 2), f"{fmt(min(ccc), 2)}--{fmt(max(ccc), 2)}"])
        if metric == "fst_immobile_s":
            N["iccImm"] = fmt(icc, 2)
            N["cccImmMin"], N["cccImmMax"] = fmt(min(ccc), 2), fmt(max(ccc), 2)
            spread = y.max(axis=1) - y.min(axis=1)
            ratio = y.max(axis=1) / np.maximum(y.min(axis=1), 1e-9)
            N["immSpreadMedian"] = fmt(np.median(spread), 0)
            N["immSpreadMax"] = fmt(spread.max(), 0)
            N["immSpreadMaxVideo"] = w.index[int(np.argmax(spread))].replace("_", r"\_")
            N["immRatioMax"] = fmt(ratio.max(), 0)
            means = y.mean(axis=0)
            N["raterMeanLow"], N["raterMeanHigh"] = fmt(means.min(), 0), fmt(means.max(), 0)
            # rank agreement: would the raters order the animals the same way?
            ranks = w.rank().to_numpy()
            rho = [np.corrcoef(ranks[:, i], ranks[:, j])[0, 1] for i, j in combinations(range(len(rater_names)), 2)]
            N["rhoImmMin"], N["rhoImmMax"] = fmt(min(rho), 2), fmt(max(rho), 2)
            # the rater who agrees least with the others, and the ICC without them
            C = pd.DataFrame(np.nan, index=rater_names, columns=rater_names)
            for i, j in combinations(range(len(rater_names)), 2):
                C.iloc[i, j] = C.iloc[j, i] = lins_ccc(y[:, i], y[:, j])
            odd = C.mean().idxmin()
            N["oddRater"] = odd
            N["iccImmWithoutOdd"] = fmt(icc_a1_k(w.drop(columns=odd).to_numpy(float)), 2)
            with open(GEN / "fst_raters_bars.tex", "w") as f:  # lowest-to-highest rater per video
                for i, (_, row) in enumerate(w.iterrows()):
                    f.write(f"\\draw[bandc, line width=5pt] (axis cs:{i},{row.min():.2f}) "
                            f"-- (axis cs:{i},{row.max():.2f});\n")
            with open(GEN / "fst_raters.dat", "w") as f:
                f.write("x video " + " ".join(r.replace(" ", "") for r in rater_names) + " lo hi\n")
                for i, (vid, row) in enumerate(w.iterrows()):
                    f.write(f"{i} {vid.replace('_', '')} " + " ".join(f"{v:.2f}" for v in row)
                            + f" {row.min():.2f} {row.max():.2f}\n")
        if metric == "fst_immobility_latency_s":
            N["iccLat"] = fmt(icc, 2)
        if metric == "fst_immobile_bins":
            N["iccBins"] = fmt(icc, 2)
    # same raters with bouts shorter than fst.min_immobile_s dropped (one shared bout rule)
    long_ev = events[events.stop - events.start >= cfg.fst.min_immobile_s]
    hum_b = rater_long(long_ev, cfg)
    for metric, key in [("fst_immobile_s", "Imm"), ("fst_immobility_latency_s", "Lat")]:
        w = hum_b[hum_b.metric == metric].pivot(index="video_id", columns="tool", values="value").loc[labelled, rater_names]
        N[f"icc{key}MinBout"] = fmt(icc_a1_k(w.to_numpy(float)), 2)
    tabular(GEN / "tab_fst_reliability.tex",
            ["Metric", *rater_names, "ICC(A,1)", "pairwise CCC"], rel_rows, "l" + "r" * (len(rater_names) + 2))

    # rater coding style: number of bouts and median bout length
    ev = events.assign(d=events.stop - events.start)
    style = ev.groupby("rater").agg(n=("d", "size"), med=("d", "median"), short=("d", lambda d: (d < 1).mean()))
    tabular(GEN / "tab_rater_style.tex", ["", "bouts coded", "median bout (s)", "bouts $<$ 1 s"],
            [[r, f"{int(s.n)}", fmt(s.med, 1), f"{100 * s.short:.0f}\\%"] for r, s in style.iterrows()], "lrrr")

    # ---- 2. automated FST
    params = TrackerParams.from_dict(cfg.tracker)
    auto = []
    for vid in FST_VIDEOS:
        p = REP / "fst" / "tracks" / f"{vid}.csv"
        if a.retrack or not p.exists():
            track(DATA / f"{vid}.mp4", cfg.zones, params, cfg.mask_margin_px).to_csv(p, index=False)
        df = load_trajectory(p)
        if vid not in cfg.sessions:
            # no labels: start when the animal is first tracked for 1 s (it is placed in the
            # water after recording starts), same length as FST_1's window
            ok = df.x_px.notna().to_numpy()
            first = next(a0 for a0, b0 in runs(ok) if b0 - a0 >= 25)
            start = float(df.time_s.iloc[first])
            dur = min(cfg.sessions["FST_1"].duration_s, float(df.time_s.max()) - start)
            cfg.sessions[vid] = Session(start, dur, None)
            N[f"start{vid.replace('_', '')}"] = fmt(start, 1)
        auto.append(fst_metrics(df, cfg, vid, "opencv"))
        N[f"tracked{vid.replace('_', '')}"] = fmt(100 * df.x_px.notna().mean(), 1)
        N[f"area{vid.replace('_', '')}"] = fmt(df.area_px.median(), 0)
    auto = pd.concat(auto, ignore_index=True)
    auto.to_csv(GEN / "fst_opencv_metrics.csv", index=False)

    def val(long, vid, metric, tool=None):
        sel = (long.video_id == vid) & (long.metric == metric)
        if tool:
            sel &= long.tool == tool
        return float(long.loc[sel, "value"].iloc[0])

    rows = []
    for vid in FST_VIDEOS:
        hv = [val(hum, vid, "fst_immobile_s", r) for r in rater_names] if vid in windows else []
        hl = [val(hum, vid, "fst_immobility_latency_s", r) for r in rater_names] if vid in windows else []
        hb = [val(hum, vid, "fst_immobile_bins", r) for r in rater_names] if vid in windows else []
        rng = lambda v, nd=1: f"{fmt(min(v), nd)}--{fmt(max(v), nd)}" if v else "no labels"
        rows.append([vid.replace("_", r"\_"), fmt(cfg.sessions[vid].duration_s, 0),
                     fmt(val(auto, vid, "fst_immobile_s")), rng(hv),
                     fmt(val(auto, vid, "fst_immobility_latency_s")), rng(hl),
                     fmt(val(auto, vid, "fst_immobile_bins"), 0), rng(hb, 0)])
    tabular(GEN / "tab_fst_auto.tex",
            ["Video", "window (s)", "RATEL", "raters", "RATEL", "raters", "RATEL", "raters"], rows, "lrrrrrrr")
    N["autoImmFSTone"] = fmt(val(auto, "FST_1", "fst_immobile_s"))
    N["autoImmFSTtwo"] = fmt(val(auto, "FST_2", "fst_immobile_s"))
    hv1 = [val(hum, "FST_1", "fst_immobile_s", r) for r in rater_names]
    N["humImmFSToneMin"], N["humImmFSToneMax"] = fmt(min(hv1)), fmt(max(hv1))

    # ---- 3. FST_1 frame by frame
    df = load_trajectory(REP / "fst" / "tracks" / "FST_1.csv")
    s = cfg.sessions["FST_1"]
    keep = (df.time_s >= s.start_s) & (df.time_s < s.start_s + s.duration_s)
    sub = df[keep]
    t = sub.time_s.to_numpy() - s.start_s
    durations, ratio, imm = score_immobility(t, sub.motion_px.to_numpy(), sub.area_px.to_numpy(), cfg, s.duration_s)
    ev1 = events[events.video_id == "FST_1"]
    rater_masks = {r: in_intervals(t + s.start_s, list(zip(g.start, g.stop))) for r, g in ev1.groupby("rater")}
    N["kappaDefaultMax"] = fmt(max(kappa(imm, rater_masks[r]) for r in rater_names), 2)

    # does the motion signal separate floating from not floating? (threshold-free)
    votes = np.sum([rater_masks[r] for r in rater_names], axis=0)
    for key, sel in [("Float", votes == len(rater_names)), ("Mobile", votes == 0)]:
        q = np.nanpercentile(ratio[sel], [5, 50, 95])
        N[f"ratio{key}Lo"], N[f"ratio{key}Med"], N[f"ratio{key}Hi"] = (fmt(v, 2) for v in q)
    aucs = [auc(-ratio, rater_masks[r]) for r in rater_names]
    N["aucMin"], N["aucMax"] = fmt(min(aucs), 2), fmt(max(aucs), 2)
    N["trackedWindow"] = fmt(100 * np.isfinite(sub.motion_px.to_numpy()).mean(), 1)

    sec = np.floor(t).astype(int)
    trace = pd.Series(ratio).groupby(sec).mean()
    with open(GEN / "fst1_motion.dat", "w") as f:
        f.write("t ratio\n")
        for k, v in trace.items():
            f.write(f"{k + 0.5:.1f} {max(v, 1e-3) if np.isfinite(v) else 'nan'}\n")
    N["thrDefault"] = fmt(cfg.fst.motion_threshold, 2)
    N["minBout"] = fmt(cfg.fst.min_immobile_s, 1)

    # threshold sweep (exploratory)
    thr0 = cfg.fst.motion_threshold
    with open(GEN / "fst1_sweep.dat", "w") as f:
        f.write("thr imm kmean kmin kmax\n")
        best = (None, -1)
        for thr in SWEEP:
            cfg.fst.motion_threshold = float(thr)
            d, _, m = score_immobility(t, sub.motion_px.to_numpy(), sub.area_px.to_numpy(), cfg, s.duration_s)
            ks = [kappa(m, rater_masks[r]) for r in rater_names]
            f.write(f"{thr:.5f} {d[m].sum():.2f} {np.mean(ks):.4f} {min(ks):.4f} {max(ks):.4f}\n")
            if np.mean(ks) > best[1]:
                best = (thr, np.mean(ks))
    N["sweepBestThr"], N["sweepBestKappa"] = fmt(best[0], 3), fmt(best[1], 2)
    # FST_1-tuned threshold applied to FST_1 (in-sample) and FST_2 (unlabelled)
    cfg.fst.motion_threshold = float(best[0])
    for vid in FST_VIDEOS:
        m = fst_metrics(load_trajectory(REP / "fst" / "tracks" / f"{vid}.csv"), cfg, vid, "opencv")
        key = vid.replace("_", "")
        N[f"tunedImm{key}"] = fmt(val(m, vid, "fst_immobile_s"))
        N[f"tunedLat{key}"] = fmt(val(m, vid, "fst_immobility_latency_s"))
        N[f"tunedBins{key}"] = fmt(val(m, vid, "fst_immobile_bins"), 0)
    _, _, imm_tuned = score_immobility(t, sub.motion_px.to_numpy(), sub.area_px.to_numpy(), cfg, s.duration_s)
    tools = {**rater_masks, r"RATEL$^\dagger$": imm_tuned}
    names = list(tools)
    K = pd.DataFrame(np.nan, index=names, columns=names)
    for i, j in combinations(names, 2):
        K.loc[i, j] = K.loc[j, i] = kappa(tools[i], tools[j])
    hh = [K.loc[i, j] for i, j in combinations(rater_names, 2)]
    hc = [K.loc[r, names[-1]] for r in rater_names]
    N["kappaHHMin"], N["kappaHHMax"] = fmt(min(hh), 2), fmt(max(hh), 2)
    N["kappaTunedMin"], N["kappaTunedMax"] = fmt(min(hc), 2), fmt(max(hc), 2)
    tabular(GEN / "tab_kappa.tex", ["", *names],
            [[n, *["" if i == j else fmt(K.loc[n, m], 2) for j, m in enumerate(names)]] for i, n in enumerate(names)],
            "l" + "r" * len(names))

    # ethogram (TikZ, inside a pgfplots axis) and the 1-s motion trace
    with open(GEN / "etho_fst1.tex", "w") as f:
        for row, name in enumerate(reversed(names)):
            mask = tools[name]
            colour = "human" if name.startswith("Rater") else "opencv"
            for a0, b0 in runs(mask):
                x0, x1 = t[a0], t[b0 - 1] + durations[b0 - 1]
                f.write(f"\\fill[{colour}] (axis cs:{x0:.2f},{row + 0.12}) rectangle (axis cs:{x1:.2f},{row + 0.88});\n")
    cfg.fst.motion_threshold = thr0
    N["hhLo"], N["hhHi"] = f"{min(hh):.3f}", f"{max(hh):.3f}"
    N["humLo"], N["humHi"] = f"{min(hv1):.2f}", f"{max(hv1):.2f}"

    # ---- 4. OFT (RATEL vs DLC)
    pos = pd.read_csv(OFT / "positions.csv")
    agr = pd.read_csv(OFT / "agreement.csv", keep_default_na=False, na_values=[""])
    agr["zone"] = agr["zone"].fillna("")
    tabular(GEN / "tab_oft_positions.tex",
            ["Video", "frames", "RATEL tracked", "both valid", "median (px)", "95th pct (px)", "lag (frames)"],
            [[r.video_id.replace("_", r"\_"), f"{r.frames_a}", f"{100 * r.opencv_tracked:.1f}\\%",
              f"{100 * r.both_valid:.1f}\\%", fmt(r.median_px), fmt(r.p95_px), f"{r.best_lag_frames}"]
             for r in pos.itertuples()], "lrrrrrr")
    N["oftMedianPxMin"], N["oftMedianPxMax"] = fmt(pos.median_px.min()), fmt(pos.median_px.max())
    cfgs = {v: load_config(OFT / "configs" / f"{v}.toml") for v in pos.video_id}
    N["oftPxPerMm"] = f"{np.mean([c.px_per_m for c in cfgs.values()]) / 1000:.2f}"
    N["oftMedianMm"] = fmt(pos.median_px.mean() / np.mean([c.px_per_m for c in cfgs.values()]) * 1000, 0)
    label = {"total_distance_m": "Total distance (m)", "mean_speed_m_s": "Mean speed (m/s)",
             "immobile_time_s": "Immobile time (s)", "time_pct": "Time (\\%)", "time_s": "Time (s)",
             "entries": "Entries", "latency_s": "Latency (s)", "distance_m": "Distance (m)"}
    order = ["total_distance_m", "mean_speed_m_s", "immobile_time_s", "time_pct", "entries", "latency_s", "distance_m"]
    agr = agr[agr.metric.isin(order) & ~((agr.metric == "latency_s") & (agr.zone == "periphery"))].copy()
    agr["o"] = agr.metric.map(order.index)
    rows = []
    for r in agr.sort_values(["o", "zone"]).itertuples():
        nd = 3 if r.metric == "mean_speed_m_s" else 2
        rows.append([label[r.metric], r.zone or "arena", fmt(r.mean_a, nd), fmt(r.mean_b, nd), fmt(r.bias, nd),
                     fmt(r.bias_pct, 1), f"{fmt(r.loa_low, nd)} to {fmt(r.loa_high, nd)}", fmt(r.ccc, 2)])
    tabular(GEN / "tab_oft_agreement.tex",
            ["Metric", "zone", "DLC", "RATEL", "bias", "bias \\%", "95\\% LoA", "CCC"], rows, "llrrrrrr")
    imm = agr[agr.metric == "immobile_time_s"].iloc[0]
    N["oftImmBiasPct"] = fmt(imm.bias_pct, 0)
    lat = agr[(agr.metric == "latency_s") & (agr.zone == "center")].iloc[0]
    N["oftLatBias"] = fmt(lat.bias, 1)
    dist = agr[agr.metric == "total_distance_m"].iloc[0]
    N["oftDistBiasPct"] = fmt(dist.bias_pct, 1)
    ent = agr[(agr.metric == "entries") & (agr.zone == "center")].iloc[0]
    N["oftEntBias"] = fmt(ent.bias, 2)

    # trajectory overlay, first 60 s of the analysed window of one video
    vid = "OFT_5"
    c = cfgs[vid]
    for tool in ("opencv", "dlc"):
        d = load_trajectory(OFT / "tracks" / tool / f"{vid}.csv")
