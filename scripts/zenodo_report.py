# --------------------------------------------------------------------------- helpers


def icc_a1_k(y: np.ndarray) -> float:
    """ICC(A,1), two-way, absolute agreement, single rater, for an n x k matrix (McGraw & Wong 1996)."""
    y = y[np.isfinite(y).all(axis=1)]
    n, k = y.shape
    if n < 2:
        return np.nan
    grand = y.mean()
    ss_rows = k * ((y.mean(axis=1) - grand) ** 2).sum()
    ss_cols = n * ((y.mean(axis=0) - grand) ** 2).sum()
    ss_err = ((y - grand) ** 2).sum() - ss_rows - ss_cols
    msr, msc = ss_rows / (n - 1), ss_cols / (k - 1)
    mse = ss_err / ((n - 1) * (k - 1))
    return float((msr - mse) / (msr + (k - 1) * mse + k * (msc - mse) / n))


def kappa(a: np.ndarray, b: np.ndarray) -> float:
    a, b = np.asarray(a, bool), np.asarray(b, bool)
    po = (a == b).mean()
    pe = a.mean() * b.mean() + (1 - a.mean()) * (1 - b.mean())
    return float((po - pe) / (1 - pe)) if pe < 1 else np.nan


def auc(score: np.ndarray, label: np.ndarray) -> float:
    """Area under the ROC curve (Mann-Whitney): P(score of a positive frame > score of a negative frame)."""
    ok = np.isfinite(score)
    score, label = score[ok], np.asarray(label, bool)[ok]
    r = pd.Series(score).rank().to_numpy()
    n1, n0 = label.sum(), (~label).sum()
    return float((r[label].sum() - n1 * (n1 + 1) / 2) / (n1 * n0)) if n1 and n0 else np.nan


def in_intervals(t: np.ndarray, iv: list[tuple[float, float]]) -> np.ndarray:
    out = np.zeros(len(t), bool)
    for a, b in iv:
        out |= (t >= a) & (t < b)
    return out


def fmt(v, nd=1) -> str:
    if v is None or not np.isfinite(v):
        return "--"
    out = f"{abs(v):.{nd}f}"
    return f"$-${out}" if v < 0 and float(out) != 0 else out


class Numbers:
    def __init__(self):
        self.lines = ["% generated by scripts/zenodo_report.py -- do not edit"]

    def __setitem__(self, name, value):
        # TeX control sequences cannot contain digits: FST1 -> FSTOne
        words = "Zero One Two Three Four Five Six Seven Eight Nine".split()
        name = re.sub(r"\d", lambda m: words[int(m.group())], name)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def flag(self, name, on: bool):
        """\\if<name> ... \\fi in the report."""
        self.lines += [f"\\newif\\if{name}", f"\\{name}{'true' if on else 'false'}"]

    def write(self, path):
        path.write_text("\n".join(self.lines) + "\n", encoding="utf-8")


def tabular(path: Path, header: list[str], rows: list[list[str]], align: str) -> None:
    lines = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + r" \\", "\\midrule"]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- FST labels


def read_fst_labels() -> tuple[pd.DataFrame, dict[str, tuple[float, float]], dict[str, str]]:
    lab = pd.read_csv(DATA / "labels" / "AllFSTLables.csv", sep=";")
    raters = {name: f"Rater {chr(65 + i)}" for i, name in enumerate(sorted(lab.Experimenter.unique()))}
    lab["rater"] = lab.Experimenter.map(raters)
    windows = {}
    for vid, g in lab[lab.type.str.match(r"Start.?End")].groupby("ID"):
        per = g.groupby("rater")["from"].agg(["min", "max"])
        windows[vid] = (float(per["min"].median()), float(per["max"].median() - per["min"].median()))
    fl = lab[lab.type == "Floating"]
    events = pd.DataFrame({"video_id": fl.ID, "behaviour": "Floating", "start": fl["from"], "stop": fl["to"],
                           "media_duration": np.nan, "rater": fl.rater})
    return events, windows, raters


def rater_long(events: pd.DataFrame, cfg) -> pd.DataFrame:
    parts = []
    for rater, ev in events.groupby("rater"):
        long = events_to_long(ev.drop(columns="rater"), cfg, fst_map={"Floating": "immobile"})
        parts.append(long.assign(tool=rater))
    return pd.concat(parts, ignore_index=True)


